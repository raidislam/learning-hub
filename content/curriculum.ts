import type { ModuleDef, TopicDef, TrackDef, Difficulty } from "@/types/curriculum";

/** "map()" -> "map", "O(n²)" -> "o-n2", "Equality: == vs ===" needs explicit slug */
export function slugify(title: string): string {
  return title
    .toLowerCase()
    .replace(/²/g, "2")
    .replace(/\(\)/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

type TopicInput = string | [title: string, slug: string];

function topics(list: TopicInput[]): TopicDef[] {
  return list.map((t) => (typeof t === "string" ? { slug: slugify(t), title: t } : { slug: t[1], title: t[0] }));
}

function mod(
  number: number,
  slug: string,
  title: string,
  difficulty: Difficulty,
  prerequisites: string[],
  summary: string,
  list: TopicInput[],
): ModuleDef {
  return {
    id: `m${String(number).padStart(2, "0")}`,
    slug,
    number,
    title,
    difficulty,
    prerequisites,
    summary,
    topics: topics(list),
  };
}

